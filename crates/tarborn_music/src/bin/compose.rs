//! Fills the music library: runs the quality-diversity search for every
//! style and writes `assets/music/library/<style>.ron`. With `--previews
//! <dir> [tunes]`, also renders the best `tunes` (default 3) of each style:
//! each distinct section once per intensity layer, calm to full, then the
//! stinger.
//!
//! cargo run --release -p tarborn_music --bin compose [-- --previews <dir> [tunes]]

use tarborn_music::search::{LibraryTune, Realized, compose, realize};
use tarborn_music::style::Style;
use tarborn_music::{Fragment, MusicFile, PatchBank, Role, from_ron, render, to_ron};
use tarborn_sfx::wav;

const ASSETS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../tarborn/assets");
const STYLES: [&str; 2] = ["industrial", "forest"];

fn load<T: serde::de::DeserializeOwned>(path: &str) -> T {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("reading {path}: {e}"));
    from_ron(&text).unwrap_or_else(|e| panic!("parsing {path}: {e}"))
}

fn append(out: &mut Fragment, f: &Fragment, offset: f32) {
    for n in &f.notes {
        let mut n = n.clone();
        n.start += offset;
        out.notes.push(n);
    }
}

/// Each section once per layer, best variant of every part, then the stinger.
fn preview(style: &Style, r: &Realized) -> Fragment {
    let t = &r.tune;
    let mut out = Fragment {
        role: Role::Stinger,
        beats_per_bar: t.beats_per_bar,
        bars: 0,
        style: style.name.clone(),
        ..Fragment::default()
    };
    for layer in 0..style.layers.max(1) {
        for s in 0..t.sections.len() {
            let offset = out.beats();
            for (lp, fs) in &r.parts {
                if lp.section == s && lp.layer == layer {
                    append(&mut out, &fs[0], offset);
                }
            }
            out.bars += t.sections[s].bars;
        }
    }
    let offset = out.beats();
    append(&mut out, &r.stinger, offset);
    out.bars += r.stinger.bars;
    out
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let previews = match args.as_slice() {
        [] => None,
        [flag, dir, rest @ ..] if flag == "--previews" => {
            let n = rest
                .first()
                .map_or(3, |n| n.parse().expect("tunes is a number"));
            Some((dir.clone(), n))
        }
        _ => {
            eprintln!("usage: compose [--previews <dir> [tunes]]");
            std::process::exit(2);
        }
    };
    let file: MusicFile = load(&format!("{ASSETS}/music.ron"));
    let bank: PatchBank = load(&format!("{ASSETS}/music/patches.ron"));
    let dir = format!("{ASSETS}/music/library");
    std::fs::create_dir_all(&dir).expect("creating the library folder");
    for name in STYLES {
        let style: Style = load(&format!("{ASSETS}/music/styles/{name}.ron"));
        let start = std::time::Instant::now();
        let library = compose(&style, &file.metrics, &file.search);
        let parts: usize = library.iter().map(|t| t.parts.len()).sum();
        let variants: usize = library
            .iter()
            .flat_map(|t| &t.parts)
            .map(|p| p.variants.len())
            .sum();
        let mean = library.iter().map(|t| t.score).sum::<f32>() / library.len().max(1) as f32;
        let path = format!("{dir}/{name}.ron");
        let text = format!(
            "// GENERATED by `cargo run --release -p tarborn_music --bin compose`.\n\
             // Seeds and scores only: the grammar regenerates the notes.\n{}\n",
            to_ron(&library).expect("serializes")
        );
        std::fs::write(&path, text).expect("writing the library");
        println!(
            "{name}: {} tunes, {parts} parts, {variants} variants, mean score {mean:.3}, {:.1} s -> {path}",
            library.len(),
            start.elapsed().as_secs_f32()
        );
        for t in &library {
            println!(
                "  {:>10} {:>3.0} BPM {} {} {:?} score {:.3}",
                t.seed,
                t.bpm,
                t.key,
                if t.minor { "minor" } else { "major" },
                t.cell.1,
                t.score
            );
        }
        if let Some((out, n)) = &previews {
            std::fs::create_dir_all(out).expect("creating the preview folder");
            let mut best: Vec<&LibraryTune> = library.iter().collect();
            best.sort_by(|a, b| b.score.total_cmp(&a.score));
            for (i, t) in best.iter().take(*n).enumerate() {
                let r = realize(&style, t);
                let settings = tarborn_music::RenderSettings {
                    bpm: r.tune.bpm,
                    swing: r.tune.swing,
                    ..file.render.clone()
                };
                let samples =
                    render(&preview(&style, &r), &bank, &settings, t.seed).expect("renders");
                let wav_path = format!("{out}/{name}-{}-{:.0}bpm.wav", i + 1, t.bpm);
                std::fs::write(&wav_path, wav::encode(&samples, settings.sample_rate))
                    .expect("writing the wav");
                println!(
                    "  preview {:.1} s -> {wav_path}",
                    samples.len() as f32 / settings.sample_rate as f32
                );
            }
        }
    }
}
