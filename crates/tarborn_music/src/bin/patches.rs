//! Generates the instrument patches from their genomes and writes
//! `assets/music/patches.ron`, plus WAV previews when given a folder.
//!
//! cargo run --release -p tarborn_music --bin patches -- [preview-dir]
//!     [--instruments <instruments.ron>] [--out <patches.ron>]

use std::path::PathBuf;
use tarborn_music::patches::{InstrumentFile, bank, generate_all};
use tarborn_music::{from_ron, to_ron};
use tarborn_sfx::wav;

const ASSETS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../tarborn/assets/music");

const HEADER: &str = "// GENERATED by `cargo run --release -p tarborn_music --bin patches`
// from instruments.ron. Don't edit by hand: change the genomes there and
// regenerate.
//
// Per patch: sound (a tarborn_sfx sound, as in assets/sfx.ron), pitched,
// root (MIDI pitch it is written at), filter_tracking (0 fixed .. 1 follows
// pitch), gate (hold for the note instead of ringing out), gain.
";

fn main() {
    let mut instruments = PathBuf::from(format!("{ASSETS}/instruments.ron"));
    let mut out = PathBuf::from(format!("{ASSETS}/patches.ron"));
    let mut previews = None;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--instruments" => instruments = args.next().expect("a path").into(),
            "--out" => out = args.next().expect("a path").into(),
            _ => previews = Some(PathBuf::from(arg)),
        }
    }
    let text = std::fs::read_to_string(&instruments)
        .unwrap_or_else(|e| panic!("reading {}: {e}", instruments.display()));
    let file: InstrumentFile =
        from_ron(&text).unwrap_or_else(|e| panic!("parsing {}: {e}", instruments.display()));
    let generated = generate_all(&file);

    println!(
        "{:12} {:>8} {:>8} {:>9} {:>6}  miss",
        "instrument", "attack", "decay", "centroid", "noise"
    );
    let mut misses = 0;
    for (name, g) in &generated {
        let d = g.descriptors;
        let t = &file.instruments[name].targets;
        println!(
            "{name:12} {:7.1}ms {:7.0}ms {:8.0}Hz {:6.2}  {:.3}   targets {:.0}-{:.0}ms {:.0}-{:.0}ms {:.0}-{:.0}Hz {:.2}-{:.2}",
            d.attack * 1000.0,
            d.decay * 1000.0,
            d.centroid,
            d.noisiness,
            g.miss,
            t.attack[0] * 1000.0,
            t.attack[1] * 1000.0,
            t.decay[0] * 1000.0,
            t.decay[1] * 1000.0,
            t.centroid[0],
            t.centroid[1],
            t.noisiness[0],
            t.noisiness[1],
        );
        if g.miss > 0.0 {
            misses += 1;
        }
    }

    let body = to_ron(&bank(&generated)).expect("patches serialize");
    std::fs::write(&out, format!("{HEADER}{body}\n")).expect("writing patches");
    println!("wrote {}", out.display());

    if let Some(dir) = previews {
        std::fs::create_dir_all(&dir).expect("creating the preview folder");
        let rate = file.search.sample_rate;
        for (name, g) in &generated {
            let instrument = &file.instruments[name];
            // Pitched instruments: root, a fifth and an octave up. Drums: three hits.
            let steps: &[f32] = if instrument.pitched {
                &[0.0, 7.0, 12.0]
            } else {
                &[0.0, 0.0, 0.0]
            };
            let gap = (0.5 * rate as f32) as usize;
            let mut samples = Vec::new();
            for (i, step) in steps.iter().enumerate() {
                let note = g
                    .patch
                    .voiced(instrument.root + step, instrument.measure_length, 440.0)
                    .render(rate);
                let at = i * gap;
                if samples.len() < at + note.len() {
                    samples.resize(at + note.len(), 0.0);
                }
                for (s, n) in samples[at..].iter_mut().zip(note) {
                    *s += n * g.patch.gain;
                }
            }
            for s in &mut samples {
                *s = tarborn_sfx::soft_limit(*s);
            }
            std::fs::write(dir.join(format!("{name}.wav")), wav::encode(&samples, rate))
                .expect("writing a preview");
        }
        println!("previews in {}", dir.display());
    }
    if misses > 0 {
        eprintln!("{misses} instrument(s) landed outside their targets");
        std::process::exit(1);
    }
}
